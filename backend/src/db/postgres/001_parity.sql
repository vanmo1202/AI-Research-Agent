-- PostgreSQL parity schema. Opaque TEXT identifiers preserve non-UUID legacy IDs.
CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA public;

CREATE TABLE requests (
        id TEXT PRIMARY KEY, topic TEXT NOT NULL, goal TEXT NOT NULL,
        scope TEXT, output_length TEXT, status TEXT,
        created_at TIMESTAMPTZ, updated_at TIMESTAMPTZ
    , owner_id TEXT NOT NULL DEFAULT 'workspace',
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE schema_migrations (version TEXT PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE documents (id TEXT PRIMARY KEY, owner_id TEXT NOT NULL, filename TEXT NOT NULL,
      storage_name TEXT NOT NULL, sha256 TEXT NOT NULL, byte_size BIGINT NOT NULL CHECK(byte_size>0),
      page_count INTEGER NOT NULL DEFAULT 0, status TEXT NOT NULL CHECK(status IN ('pending','processing','ready','failed')),
      error_code TEXT, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL, deleted_at TIMESTAMPTZ,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE users (
    id TEXT PRIMARY KEY, email TEXT NOT NULL ,
    name TEXT NOT NULL, password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user' CHECK(role IN ('user','admin')),
    status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','disabled')),
    created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE chat_turn_usage (chat_id TEXT NOT NULL, turn_id TEXT NOT NULL,
      search_calls INTEGER NOT NULL DEFAULT 0, llm_calls INTEGER NOT NULL DEFAULT 0,
      input_bytes BIGINT NOT NULL DEFAULT 0, output_tokens BIGINT NOT NULL DEFAULT 0,
      page_fetches INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(chat_id,turn_id),
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE chat_daily_usage (subject TEXT NOT NULL, day TEXT NOT NULL,
      search_calls INTEGER NOT NULL DEFAULT 0, llm_calls INTEGER NOT NULL DEFAULT 0,
      input_bytes BIGINT NOT NULL DEFAULT 0, output_tokens BIGINT NOT NULL DEFAULT 0,
      page_fetches INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(subject,day),
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE plans (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        request_id TEXT NOT NULL REFERENCES requests(id),
        question_id TEXT NOT NULL, research_question TEXT NOT NULL,
        search_query TEXT NOT NULL, created_at TIMESTAMPTZ
    ,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE sources (
        id TEXT PRIMARY KEY,
        request_id TEXT NOT NULL REFERENCES requests(id),
        query TEXT NOT NULL, title TEXT, url TEXT NOT NULL,
        normalized_url TEXT NOT NULL, snippet TEXT, content TEXT, provider TEXT,
        collected_at TIMESTAMPTZ NOT NULL, title_vi TEXT, snippet_vi TEXT, content_vi TEXT, source_language TEXT, translation_status TEXT, translation_hash TEXT,
        UNIQUE(request_id, normalized_url)
    ,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE reports (
        id TEXT PRIMARY KEY, request_id TEXT NOT NULL UNIQUE, title TEXT,
        language TEXT DEFAULT 'vi', style TEXT, output_length TEXT, content TEXT NOT NULL,
        references_json JSONB, created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (request_id) REFERENCES requests(id)
    ,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE evidence_cache (
        request_id TEXT NOT NULL REFERENCES requests(id), question_id TEXT NOT NULL,
        input_hash TEXT NOT NULL, evidence_json JSONB NOT NULL,
        PRIMARY KEY(request_id, question_id, input_hash)
    ,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE analysis_results (
        request_id TEXT PRIMARY KEY REFERENCES requests(id), metadata_json JSONB NOT NULL
    ,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE research_runs (
 id TEXT PRIMARY KEY, request_id TEXT NOT NULL REFERENCES requests(id), input_snapshot_json JSONB NOT NULL,
 status TEXT NOT NULL CHECK(status IN ('queued','running','completed','partial','failed','cancelled')),
 current_stage TEXT, current_round INTEGER NOT NULL DEFAULT 0, last_successful_stage TEXT,
 created_at TIMESTAMPTZ NOT NULL, started_at TIMESTAMPTZ, completed_at TIMESTAMPTZ, updated_at TIMESTAMPTZ NOT NULL,
 error_code TEXT, error_message TEXT, idempotency_key TEXT NOT NULL, orchestration TEXT NOT NULL DEFAULT 'backend',
 llm_calls INTEGER NOT NULL DEFAULT 0, search_calls INTEGER NOT NULL DEFAULT 0,
 UNIQUE(request_id,idempotency_key),
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE document_pages (document_id TEXT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
      page INTEGER NOT NULL CHECK(page>0), content TEXT NOT NULL, PRIMARY KEY(document_id,page),
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE research_documents (request_id TEXT NOT NULL REFERENCES requests(id), document_id TEXT NOT NULL REFERENCES documents(id), owner_id TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL, PRIMARY KEY(request_id,document_id),
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE document_ingestion_jobs (id TEXT PRIMARY KEY, document_id TEXT NOT NULL REFERENCES documents(id), status TEXT NOT NULL CHECK(status IN ('pending','processing','ready','failed')), attempts INTEGER NOT NULL DEFAULT 0, generation INTEGER NOT NULL DEFAULT 0, lease_until BIGINT, error_code TEXT, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE user_sessions (
    id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE, created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL, revoked_at TIMESTAMPTZ,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE "chat_sessions" (id TEXT PRIMARY KEY, owner_id TEXT NOT NULL, request_id TEXT REFERENCES requests(id), title TEXT NOT NULL, scope TEXT NOT NULL CHECK(scope IN ('documents','research','combined')), document_ids_json JSONB NOT NULL, memory_ids_json JSONB NOT NULL DEFAULT '[]', busy_until BIGINT NOT NULL DEFAULT 0, active_token TEXT, created_at TIMESTAMPTZ NOT NULL, auto_research BOOLEAN NOT NULL DEFAULT false, internet_enabled BOOLEAN NOT NULL DEFAULT false,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE chunks (
        id TEXT PRIMARY KEY, request_id TEXT NOT NULL, source_id TEXT NOT NULL,
        chunk_index INTEGER NOT NULL, content TEXT NOT NULL, char_count INTEGER,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (request_id) REFERENCES requests(id), FOREIGN KEY (source_id) REFERENCES sources(id),
        UNIQUE(source_id, chunk_index)
    ,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE stage_jobs (
 id TEXT PRIMARY KEY, run_id TEXT NOT NULL REFERENCES research_runs(id), stage TEXT NOT NULL,
 status TEXT NOT NULL CHECK(status IN ('queued','running','succeeded','retry_waiting','failed','cancelled')),
 attempts INTEGER NOT NULL DEFAULT 0, max_attempts INTEGER NOT NULL DEFAULT 3,
 idempotency_key TEXT NOT NULL, locked_by TEXT, locked_until TIMESTAMPTZ, heartbeat_at TIMESTAMPTZ,
 input_json JSONB NOT NULL, output_json JSONB, error_json JSONB, created_at TIMESTAMPTZ NOT NULL,
 started_at TIMESTAMPTZ, completed_at TIMESTAMPTZ, available_at TIMESTAMPTZ NOT NULL, generation INTEGER NOT NULL DEFAULT 0,
 UNIQUE(run_id,idempotency_key),
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE source_versions (
 id TEXT PRIMARY KEY, run_id TEXT NOT NULL REFERENCES research_runs(id), query TEXT NOT NULL, title TEXT, url TEXT NOT NULL,
 normalized_url TEXT NOT NULL, provider TEXT, original_content TEXT NOT NULL, display_content_vi TEXT,
 content_hash TEXT NOT NULL, language TEXT, translation_status TEXT, collected_at TIMESTAMPTZ NOT NULL,
 UNIQUE(run_id,normalized_url),
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE run_events (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, run_id TEXT NOT NULL REFERENCES research_runs(id),
 stage TEXT, event_type TEXT NOT NULL, message TEXT NOT NULL, metadata_json JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE document_chunks (id TEXT PRIMARY KEY, document_id TEXT NOT NULL, page INTEGER NOT NULL,
      chunk_index INTEGER NOT NULL, content TEXT NOT NULL, content_hash TEXT NOT NULL,
      FOREIGN KEY(document_id,page) REFERENCES document_pages(document_id,page) ON DELETE CASCADE,
      UNIQUE(document_id,page,chunk_index),
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE "chat_messages" (id TEXT PRIMARY KEY, chat_id TEXT NOT NULL REFERENCES "chat_sessions"(id) ON DELETE CASCADE, role TEXT NOT NULL CHECK(role IN ('user','assistant')), content TEXT NOT NULL, citations_json JSONB NOT NULL DEFAULT '[]', turn_id TEXT, status TEXT NOT NULL CHECK(status IN ('pending','complete','failed')), created_at TIMESTAMPTZ NOT NULL, research_json JSONB NOT NULL DEFAULT '{}', UNIQUE(chat_id,turn_id,role),
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE chat_web_sources (
    id TEXT PRIMARY KEY, owner_id TEXT NOT NULL, chat_id TEXT REFERENCES chat_sessions(id) ON DELETE SET NULL,
    turn_id TEXT NOT NULL, question TEXT NOT NULL, title TEXT NOT NULL, url TEXT NOT NULL,
    content TEXT NOT NULL, content_hash TEXT NOT NULL, retrieved_at TIMESTAMPTZ NOT NULL, provider TEXT NOT NULL,
    UNIQUE(chat_id,turn_id,url),
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE evidence (
        id TEXT PRIMARY KEY, request_id TEXT NOT NULL, source_id TEXT NOT NULL,
        chunk_id TEXT, research_question TEXT, evidence_text TEXT NOT NULL,
        relevance_score DOUBLE PRECISION, reason TEXT, citation_label TEXT,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (request_id) REFERENCES requests(id), FOREIGN KEY (source_id) REFERENCES sources(id),
        FOREIGN KEY (chunk_id) REFERENCES chunks(id)
    ,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE source_chunks_v2 (id TEXT PRIMARY KEY, run_id TEXT NOT NULL REFERENCES research_runs(id),
 source_version_id TEXT NOT NULL REFERENCES source_versions(id), chunk_index INTEGER NOT NULL, content TEXT NOT NULL,
 UNIQUE(source_version_id,chunk_index),
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE analysis_versions (id TEXT PRIMARY KEY, run_id TEXT NOT NULL REFERENCES research_runs(id),
 job_id TEXT NOT NULL UNIQUE REFERENCES stage_jobs(id), source_snapshot_hash TEXT NOT NULL,
 evidence_json JSONB NOT NULL, coverage_status TEXT NOT NULL, gaps_json JSONB NOT NULL, created_at TIMESTAMPTZ NOT NULL,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE dispatch_outbox (id TEXT PRIMARY KEY, run_id TEXT NOT NULL REFERENCES research_runs(id),
 job_id TEXT NOT NULL UNIQUE REFERENCES stage_jobs(id), event_type TEXT NOT NULL, payload_json JSONB NOT NULL,
 status TEXT NOT NULL, attempts INTEGER NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL, sent_at TIMESTAMPTZ,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE "agent_memories" (id TEXT PRIMARY KEY, owner_id TEXT NOT NULL, request_id TEXT REFERENCES requests(id), message_id TEXT REFERENCES "chat_messages"(id) ON DELETE SET NULL, kind TEXT NOT NULL CHECK(kind IN ('research','cross_research')), content TEXT NOT NULL, content_hash TEXT NOT NULL, status TEXT NOT NULL CHECK(status IN ('candidate','verified','rejected','stale')), verification_json JSONB NOT NULL DEFAULT '{}', last_checked_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL, UNIQUE(owner_id,request_id,content_hash),
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE report_versions (id TEXT PRIMARY KEY, run_id TEXT NOT NULL REFERENCES research_runs(id),
 job_id TEXT NOT NULL UNIQUE REFERENCES stage_jobs(id), analysis_version_id TEXT NOT NULL REFERENCES analysis_versions(id),
 content TEXT NOT NULL, references_json JSONB NOT NULL, citation_validation_json JSONB NOT NULL,
 status TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE "memory_evidence_links" (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, memory_id TEXT NOT NULL REFERENCES "agent_memories"(id) ON DELETE CASCADE, kind TEXT NOT NULL CHECK(kind IN ('document','evidence','source')), reference_id TEXT NOT NULL, document_id TEXT, page INTEGER, source_id TEXT, version_hash TEXT NOT NULL, quote TEXT NOT NULL,
 legacy_position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

