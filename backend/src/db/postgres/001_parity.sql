CREATE INDEX memories_owner_status ON agent_memories(owner_id,status,updated_at);

CREATE INDEX memory_links_reference ON memory_evidence_links(kind,reference_id);

CREATE INDEX messages_chat ON chat_messages(chat_id,created_at);

CREATE UNIQUE INDEX one_active_job_per_run ON stage_jobs(run_id) WHERE status IN ('queued','running','retry_waiting');

CREATE INDEX plans_request_id ON plans(request_id);

CREATE INDEX reports_run_lookup ON report_versions(run_id);

CREATE INDEX requests_owner ON requests(owner_id,created_at);

CREATE INDEX runs_request ON research_runs(request_id,created_at);

CREATE INDEX runs_request_lookup ON research_runs(request_id);

